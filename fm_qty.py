def _parse(art):
    rows = art.strip("\n").splitlines()
    return np.array([[{"#": 1, ".": 0}.get(c, -1) for c in r.strip()] for r in rows], np.int8)


_TPL = {d: _parse(a) for d, a in DIGITS.items()}
_FADED = np.array([[int(c) * 26 for c in r.strip()] for r in FADED_ZERO.strip().splitlines()],
                  np.float32)


def _score(g, t, x, y):
    h, w = t.shape
    win = g[y:y + h, x:x + w]
    if win.shape != t.shape:
        return 0.0
    m = t >= 0
    return float(((win < 100) == (t == 1))[m].mean())


def read_qty(frame, row_top):
    """Stack quantity shown on the row's icon: int, 0 for a faded (sold-out) listing,
    or None when no number is drawn (single, unstackable item)."""
    y0, x0 = row_top + BAND_DY, BAND_X0
    g = frame[y0:y0 + BAND_H, x0:x0 + BAND_W]
    g = g.mean(axis=2, dtype=np.float32)          # plain channel mean, as the templates were built
    gx, gy = QTY_X0 - x0, QTY_DY - BAND_DY            # expected glyph origin inside the band

    # sold-out rows draw the whole icon semi-transparent: no dark outline pixels anywhere
    if not (g < 70).any():
        r = cv2.matchTemplate(g[gy - 2:gy + 24, gx - 3:gx + 22], _FADED, cv2.TM_CCOEFF_NORMED)
        return 0 if r.max() > FADED_TH else None

    x, digits = gx, ""
    while x < BAND_W - 8:
        # the first glyph is left-aligned; later ones share the previous glyph's outline
        # but per-glyph bearings vary ("11" advances 12px, "10" 8px), so search wider
        xs = range(x - 1, x + (5 if digits else 2))
        sc, d, bx = max((_score(g, t, xx, yy), d, xx) for d, t in _TPL.items()
                        for xx in xs for yy in (gy - 1, gy, gy + 1))
        if sc < DIGIT_TH:
            break
        digits += d
        x = bx + _TPL[d].shape[1] - 2
    return int(digits) if digits else None
